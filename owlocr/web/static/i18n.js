window.OwlI18n = (function () {
  let lang = 'cs';

  function setLang(value) {
    lang = Object.prototype.hasOwnProperty.call(window.OWL_STRINGS, value) ? value : 'en';
    document.documentElement.lang = lang;
  }

  function getLang() { return lang; }

  function t(key, vars) {
    const table = window.OWL_STRINGS[lang] || {};
    let text = Object.prototype.hasOwnProperty.call(table, key) ? table[key]
      : (window.OWL_STRINGS.en[key] !== undefined ? window.OWL_STRINGS.en[key] : key);
    if (vars) {
      Object.keys(vars).forEach(function (name) {
        text = text.split('{' + name + '}').join(String(vars[name]));
      });
    }
    return text;
  }

  function translateDom(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (el) { el.textContent = t(el.dataset.i18n); });
    scope.querySelectorAll('[data-i18n-title]').forEach(function (el) { el.title = t(el.dataset.i18nTitle); });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) { el.placeholder = t(el.dataset.i18nPlaceholder); });
    scope.querySelectorAll('[data-i18n-aria]').forEach(function (el) { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  }

  function nfmt(n) { return Number(n).toLocaleString(lang === 'cs' ? 'cs-CZ' : 'en-US'); }

  return { setLang: setLang, getLang: getLang, t: t, translateDom: translateDom, nfmt: nfmt };
})();
window.t = window.OwlI18n.t;
